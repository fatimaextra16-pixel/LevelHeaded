def parse_session_code(session_code):
    # Split the code into parts using the dash separator
    parts = session_code.split("-")

    # Use string indexes to extract each piece of data
    session_id = parts[1]
    hours_played = int(parts[2][:-1])  # Remove the "H" and convert to integer
    stress_level = int(parts[3][2:])  # Remove "ST" prefix
    motivation = int(parts[4][2:])  # Remove "MT" prefix
    sleep_hours = int(parts[5][2:])  # Remove "SL" prefix

    return {
        "session_id": session_id,
        "hours_played": hours_played,
        "stress_level": stress_level,
        "motivation": motivation,
        "sleep_hours": sleep_hours,
    }


def validate_code_format(session_code):
    # Iterate through each character to count dashes
    dash_count = 0
    for character in session_code:
        if character == "-":
            dash_count += 1

    # A valid code must have exactly 5 dashes (6 parts)
    return dash_count == 5


def main():
    print("LevelHeaded - Session Code Scanner")
    print("=" * 40)

    # Read real session data from the file generated by main.py
    try:
        with open("session_data.txt", "r") as file:
            lines = file.readlines()
    except OSError as error:
        print(f"WARNING: Could not read session_data.txt: {error}")
        return

    # Loop through each line (sequence of session codes)
    for line in lines:
        session_code = line.strip()

        if not validate_code_format(session_code):
            print(f"Invalid code format: {session_code}")
            continue

        try:
            session_data = parse_session_code(session_code)
        except (ValueError, IndexError):
            print(f"  WARNING: Could not read the numbers in code: {session_code}")
            continue

        print(f"\nSession {session_data['session_id']}")
        print(f"  Hours Played:    {session_data['hours_played']}")
        print(f"  Stress Level:    {session_data['stress_level']}")
        print(f"  Motivation:      {session_data['motivation']}")
        print(f"  Sleep Hours:     {session_data['sleep_hours']}")

        # Expert threshold: 5 hours of gaming
        if session_data["hours_played"] > 5:
            print("  WARNING: Take a break! Excessive gaming detected.")
        else:
            print("  Gaming time is within the set limit.")


if __name__ == "__main__":
    main()
